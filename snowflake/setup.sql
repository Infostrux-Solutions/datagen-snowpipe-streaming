-- Run once as ACCOUNTADMIN (or a role that can create users, roles and databases).
-- 1) Generate a key pair first (see README), then paste the PUBLIC key body below.

CREATE DATABASE IF NOT EXISTS KAFKA_DEMO;
CREATE SCHEMA   IF NOT EXISTS KAFKA_DEMO.STREAMING;
CREATE ROLE     IF NOT EXISTS KAFKA_CONNECTOR_ROLE;

-- The connector creates its own table, stage and pipe, so it needs CREATE rights.
GRANT USAGE        ON DATABASE KAFKA_DEMO           TO ROLE KAFKA_CONNECTOR_ROLE;
GRANT USAGE        ON SCHEMA   KAFKA_DEMO.STREAMING TO ROLE KAFKA_CONNECTOR_ROLE;
GRANT CREATE TABLE ON SCHEMA   KAFKA_DEMO.STREAMING TO ROLE KAFKA_CONNECTOR_ROLE;
GRANT CREATE STAGE ON SCHEMA   KAFKA_DEMO.STREAMING TO ROLE KAFKA_CONNECTOR_ROLE;
GRANT CREATE PIPE  ON SCHEMA   KAFKA_DEMO.STREAMING TO ROLE KAFKA_CONNECTOR_ROLE;

-- Key-pair authentication is required for Snowpipe Streaming.
CREATE USER IF NOT EXISTS KAFKA_CONNECTOR_USER
  DEFAULT_ROLE = KAFKA_CONNECTOR_ROLE
  RSA_PUBLIC_KEY = '<public key body, no BEGIN/END lines>';
GRANT ROLE KAFKA_CONNECTOR_ROLE TO USER KAFKA_CONNECTOR_USER;

